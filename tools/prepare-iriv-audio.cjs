// Combine local speech clips, pad scene boundaries, and generate matching captions/timing.
const fs = require('node:fs'), path = require('node:path');
const root = path.resolve(__dirname, '..'), rate = 22050;
function readWave(file) {
  const b = fs.readFileSync(file);
  if (b.toString('ascii', 0, 4) !== 'RIFF') throw Error('Invalid WAV: ' + file);
  let pcm;
  for (let p = 12; p + 8 <= b.length;) {
    const type = b.toString('ascii', p, p + 4), size = b.readUInt32LE(p + 4), data = p + 8;
    if (type === 'fmt ' && (b.readUInt16LE(data) !== 1 || b.readUInt16LE(data + 2) !== 1 || b.readUInt32LE(data + 4) !== rate || b.readUInt16LE(data + 14) !== 16)) throw Error('Unexpected WAV format');
    if (type === 'data') pcm = b.subarray(data, data + size);
    p = data + size + (size % 2);
  }
  if (!pcm?.length) throw Error('Empty speech: ' + file);
  // Trim synthesis padding so captions begin when speech begins; retain 80 ms around words.
  let first = 0, last = pcm.length / 2 - 1;
  while (first < last && Math.abs(pcm.readInt16LE(first * 2)) < 100) first++;
  while (last > first && Math.abs(pcm.readInt16LE(last * 2)) < 100) last--;
  first = Math.max(0, first - Math.round(rate * .08)); last = Math.min(pcm.length / 2, last + Math.round(rate * .08));
  return pcm.subarray(first * 2, last * 2);
}
function wave(pcm) {
  const h = Buffer.alloc(44); h.write('RIFF'); h.writeUInt32LE(36 + pcm.length, 4); h.write('WAVEfmt ', 8); h.writeUInt32LE(16, 16); h.writeUInt16LE(1, 20); h.writeUInt16LE(1, 22); h.writeUInt32LE(rate, 24); h.writeUInt32LE(rate * 2, 28); h.writeUInt16LE(2, 32); h.writeUInt16LE(16, 34); h.write('data', 36); h.writeUInt32LE(pcm.length, 40); return Buffer.concat([h, pcm]);
}
const clean = text => text.replaceAll('Edge A I', 'EdgeAI').replaceAll('Pi Control', 'PiControl').replaceAll('A I', 'AI').replaceAll('CPU', 'CPU').replaceAll('U S B', 'USB').replaceAll('H D M I', 'HDMI').replaceAll('P W M', 'PWM').replaceAll('N V M E', 'NVMe').replaceAll('Wi Fi', 'Wi-Fi').replaceAll('R S four eighty five', 'RS485').replaceAll('R S two thirty two', 'RS232');
const stamp = seconds => { const ms = Math.round(seconds * 1000); return `${String(Math.floor(ms / 3600000)).padStart(2, '0')}:${String(Math.floor(ms / 60000) % 60).padStart(2, '0')}:${String(Math.floor(ms / 1000) % 60).padStart(2, '0')}.${String(ms % 1000).padStart(3, '0')}`; };
for (const folder of process.argv.length > 2 ? process.argv.slice(2) : ['short-video-of-iriv-pi', 'short-video-of-iriv-edgeai', 'short-video-of-iriv-hub']) {
  const dir = path.join(root, folder), config = JSON.parse(fs.readFileSync(path.join(dir, 'narration.json'), 'utf8'));
  let start = 0, cueIndex = 0, vtt = 'WEBVTT\n\n'; const buffers = [];
  const scenes = config.scenes.map((s, i) => {
    let previousEnd = 0;
    const segments = (s.segments || [{ at: .55, text: s.text }]).map((seg, j) => {
      const pcm = readWave(path.join(root, '.tmp/video-build', folder, `${i}-${j}.wav`)), duration = pcm.length / 2 / rate;
      if (seg.at < previousEnd) throw Error('Speech segments overlap: ' + s.id);
      previousEnd = seg.at + duration;
      return { ...seg, pcm, duration };
    });
    const duration = Math.ceil(Math.max(s.minDuration, previousEnd + .65) * 30) / 30;
    if (s.id === 'inspection' && duration > 18) throw Error('Inspection speech exceeds its 18 second sequence');
    const pcm = Buffer.alloc(Math.round(duration * rate) * 2), cues = [];
    for (const seg of segments) {
      seg.pcm.copy(pcm, Math.round(seg.at * rate) * 2);
      const chunks = [];
      for (const sentence of clean(seg.text).match(/[^.!?]+[.!?]?/g) || []) {
        const words = sentence.trim().split(/\s+/), count = Math.ceil(words.length / 8), width = Math.ceil(words.length / count);
        for (let i = 0; i < words.length; i += width) chunks.push(words.slice(i, i + width).join(' '));
      }
      const weights = chunks.map(x => x.length), totalWeight = weights.reduce((a,b)=>a+b,0); let offset = 0;
      chunks.forEach((text, k) => { const a = seg.at + seg.duration * offset / totalWeight; offset += weights[k]; const b = seg.at + seg.duration * offset / totalWeight; cues.push({ start: a, end: b, text }); vtt += `${++cueIndex}\n${stamp(start + a)} --> ${stamp(start + b)}\n${text}\n\n`; });
    }
    buffers.push(pcm);
    const result = { id: s.id, start, duration, display: s.display, text: segments.map(x=>clean(x.text)).join(' '), cues };
    start += duration;
    return result;
  });
  fs.writeFileSync(path.join(dir, 'narration.wav'), wave(Buffer.concat(buffers)));
  fs.writeFileSync(path.join(dir, 'narration.js'), '// Generated by tools/build-iriv-narration.cjs from narration.json.\nconst NARRATION = ' + JSON.stringify({ product: config.product, duration: start, audio: 'narration.wav', scenes }, null, 2) + ';\n');
  fs.writeFileSync(path.join(dir, config.base + '.vtt'), vtt);
  console.log(`${config.product}: ${start.toFixed(2)} seconds, ${cueIndex} short captions`);
}
